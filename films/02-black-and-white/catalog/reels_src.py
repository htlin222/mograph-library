here = pathlib.Path(__file__).parent
segs = {s['num']: s for s in json.load(open(here / 'catalog.json'))['segs']}
rows = []
for n in range(1, 73):
    s, body = segs[n], POSTS[n]
    head = f'黑白動態全書 {n:02d}/72｜{s["title"]} {s["en"]}'
    rows.append({'num': n, 'id': f'e{n:02d}', 'title': s['title'], 'en': s['en'], 'body': body,
                 'chars': len(body), 'post': f'{head}\n{body}\n{TAGS}'})
(here / 'reels.json').write_text(json.dumps(rows, ensure_ascii=False, indent=1))
with open(here / 'reels.csv', 'w', newline='', encoding='utf-8-sig') as f:
    w = csv.DictWriter(f, fieldnames=['num', 'id', 'title', 'en', 'chars', 'post']); w.writeheader()
    for r in rows: w.writerow({k: r[k] for k in ['num', 'id', 'title', 'en', 'chars', 'post']})
md = ['# Reels 社群貼文', '', '每片一則：標題列 + 約 50 字內文 + 固定 hashtag。影片檔名對應 `eNN-*.mp4`。', '']
for r in rows:
    md += [f'## {r["num"]:02d} {r["title"]} · {r["en"]}', '', '```', r['post'], '```', '']
(here / 'reels.md').write_text('\n'.join(md))
L = [r['chars'] for r in rows]
print('posts', len(rows), 'body chars min/mean/max', min(L), round(sum(L) / len(L), 1), max(L))
